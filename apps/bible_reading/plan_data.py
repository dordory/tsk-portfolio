def _build_units():
    units = []
    for section, books in _PLAN:
        for book, ranges in books:
            for token in (ranges.split() if ranges else [""]):
                marker = None
                if token[:1] in _MARKER_PREFIXES:
                    marker = _MARKER_PREFIXES[token[0]]
                    token = token[1:]
                units.append(Unit(len(units) + 1, section, book, token, marker))
    return tuple(units)


UNITS = _build_units()
UNIT_BY_ID = {u.id: u for u in UNITS}


